import type { Phase, RoleId } from "@/types/game";
export type EnginePlayer = {
  id: string;
  userId: string | null;
  name: string;
  avatar: number;
  bot: boolean;
  role: RoleId;
  alive: boolean;
  saveUsed: boolean;
  poisonUsed: boolean;
  lastGuard: string | null;
  hunterUsed: boolean;
  findings: { round: number; target: string; wolf: boolean }[];
};
export type ActionKind =
  "wolf_suggest" | "ack" | "target" | "save" | "poison" | "pass" | "skip_discussion" | "skip_phase" | "extend_phase";
export type Intent = {
  type: ActionKind;
  target?: string;
  gameId: string;
  seq: number;
  nonce: string;
};
export type TurnHistory = {
  seq: number;
  round: number;
  phase: Phase;
  stage: "guard" | "wolf" | "seer" | "witch" | null;
  secondVote: boolean;
  at: number;
  actions: { actor: string; type: ActionKind | "unsubmitted"; target?: string }[];
  outcomes: { kind: "bite" | "protected" | "saved" | "wolf_kill" | "poison_kill" | "hunter_kill" | "vote_kill" | "no_kill"; target?: string; actor?: string }[];
};
export type EngineState = {
  id: string;
  roomId: string;
  mode: "quick" | "classic";
  revealDead: boolean;
  phase: Phase;
  seq: number;
  round: number;
  started: number;
  deadline: number | null;
  extendedSeconds?: number;
  stage: "guard" | "wolf" | "seer" | "witch" | null;
  players: EnginePlayer[];
  actions: Record<string, { type: ActionKind; target?: string }>;
  wolfPlans?: Record<string, { target: string | null; locked: boolean }>;
  protected: string[];
  bite: string | null;
  poison: string[];
  deaths: string[];
  hunters: string[];
  resume: "discussion" | "night";
  runoff: string[];
  secondVote: boolean;
  tally: Record<string, number>;
  eliminated: string | null;
  message: string;
  winner: "village" | "wolf" | null;
  requests: string[];
  history?: TurnHistory[];
  historyComplete?: boolean;
};
export type PublicGame = {
  id: string;
  roomId: string;
  phase: Phase;
  seq: number;
  round: number;
  started: number;
  deadline: number | null;
  extendedSeconds?: number;
  stage: EngineState["stage"];
  players: {
    id: string;
    name: string;
    avatar: number;
    bot: boolean;
    alive: boolean;
    revealedRole?: RoleId;
  }[];
  voted: string[];
  runoff: string[];
  secondVote: boolean;
  tally: Record<string, number>;
  deaths: string[];
  eliminated: string | null;
  hunter: string | null;
  message: string;
  winner: EngineState["winner"];
  winnerIds?: string[];
  history?: TurnHistory[];
  historyComplete?: boolean;
};
export type PrivateGame = {
  playerId: string;
  role: RoleId;
  alive: boolean;
  bot: boolean;
  wolfChoices: { playerId: string; target: string | null; locked: boolean }[];
  teammates: string[];
  saveUsed: boolean;
  poisonUsed: boolean;
  lastGuard: string | null;
  findings: EnginePlayer["findings"];
  bite: string | null;
  submitted: boolean;
  canAct: boolean;
  targets: string[];
};
export type GameView = {
  public: PublicGame;
  private: PrivateGame;
  serverNow: number;
  revision: number;
};
